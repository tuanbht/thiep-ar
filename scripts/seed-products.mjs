#!/usr/bin/env node
/* The shop's products from the templates: one per public/templates/<id> that a buyer can write (form.json) and that is
   finished (its shop picture public/thumbs/<id>.jpg and its print's target targets.mind). Each brings its shelf
   categories and search words from template.json ("categories", "tags"); the categories themselves, in shelf order,
   are supabase/categories.json. Writes supabase/seed.sql, which `pnpm db:reset` loads. It upserts every field it
   knows, prices and categories included, so rerunning it on a live database resets what was changed there: change
   PRICE_VND, template.json or categories.json instead.
     node scripts/seed-products.mjs     -> supabase/seed.sql
   Order on the shelf: flower-letter first, then the 3D acts, then the films, each alphabetically. */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TEMPLATES = path.join(ROOT, "public", "templates");
const THUMBS = path.join(ROOT, "public", "thumbs");
const CATEGORIES = path.join(ROOT, "supabase", "categories.json");
const OUT = path.join(ROOT, "supabase", "seed.sql");
const PRICE_VND = 49000;
const FIRST = "flower-letter";
const ID = /^[a-z0-9][a-z0-9_-]*$/;
const CATEGORY_ID = /^[a-z0-9][a-z0-9-]*$/;
const MAX_TAGS = 20;

const readJson = async (file) => JSON.parse(await fs.readFile(file, "utf8"));
const exists = async (file) => !!(await fs.stat(file).catch(() => null));
const sql = (v) =>
  v === null || v === undefined
    ? "null"
    : typeof v === "number" || typeof v === "boolean"
      ? String(v)
      : `'${String(v).replace(/'/g, "''")}'`;
const textArray = (list) =>
  list.length ? `array[${list.map(sql).join(", ")}]::text[]` : `'{}'::text[]`;

/** The shop's categories, in shelf order. */
export async function categories(file = CATEGORIES) {
  const list = await readJson(file);
  if (!Array.isArray(list))
    throw new Error(`${path.basename(file)}: a list of categories, please`);
  return list.map((c, i) => {
    if (!CATEGORY_ID.test(c?.id ?? "") || !c.name)
      throw new Error(
        `${path.basename(file)}: a category needs an id (a-z, 0-9, -) and a name: ${JSON.stringify(c)}`,
      );
    return {
      id: c.id,
      name: String(c.name).slice(0, 60),
      blurb: c.blurb ? String(c.blurb).slice(0, 200) : null,
      sort: (i + 1) * 10,
    };
  });
}

/** A template's search words: trimmed, lowercase, each once. */
const tagsOf = (tpl) =>
  Array.isArray(tpl.tags)
    ? [
        ...new Set(
          tpl.tags
            .map((t) => String(t).trim().toLowerCase())
            .filter((t) => t && t.length <= 40),
        ),
      ].slice(0, MAX_TAGS)
    : [];

/** The products, in shelf order. A category a template names must be one of `known`. */
export async function products(
  dir = TEMPLATES,
  known = new Set(),
  thumbs = THUMBS,
) {
  const found = [];
  for (const id of (await fs.readdir(dir)).sort()) {
    if (!ID.test(id)) continue;
    const t = path.join(dir, id);
    const needs = [
      path.join(t, "form.json"),
      path.join(t, "template.json"),
      path.join(t, "targets.mind"),
      path.join(thumbs, `${id}.jpg`),
    ];
    if (!(await Promise.all(needs.map(exists))).every(Boolean)) continue;
    const tpl = await readJson(path.join(t, "template.json")),
      form = await readJson(path.join(t, "form.json"));
    const cats = [
      ...new Set(
        Array.isArray(tpl.categories) ? tpl.categories.map(String) : [],
      ),
    ];
    const unknown = cats.filter((c) => !known.has(c));
    if (unknown.length)
      throw new Error(
        `${id}: unknown category ${unknown.join(", ")} (see supabase/categories.json)`,
      );
    found.push({
      id,
      template: id,
      design: null,
      name: String(tpl.name || id).slice(0, 120),
      blurb: form.label ? String(form.label).slice(0, 300) : null,
      kind: tpl.kind === "3d" ? "3d" : "film",
      price_vnd: PRICE_VND,
      active: true,
      tags: tagsOf(tpl),
      categories: cats,
    });
  }
  const rank = (p) => (p.id === FIRST ? 0 : p.kind === "3d" ? 1 : 2);
  found.sort((a, b) => rank(a) - rank(b) || a.id.localeCompare(b.id));
  return found.map((p, i) => ({ ...p, sort: (i + 1) * 10 }));
}

export function seedSql(list, cats = []) {
  const cols = [
    "id",
    "template",
    "design",
    "name",
    "blurb",
    "kind",
    "price_vnd",
    "active",
    "sort",
    "tags",
  ];
  const rows = list
    .map(
      (p) =>
        `  (${cols.map((c) => (c === "tags" ? textArray(p.tags ?? []) : sql(p[c]))).join(", ")})`,
    )
    .join(",\n");
  const links = list.flatMap((p) =>
    (p.categories ?? []).map((c) => `  (${sql(p.id)}, ${sql(c)})`),
  );
  const parts = [
    `-- Generated by scripts/seed-products.mjs from public/templates and supabase/categories.json: do not edit by hand.`,
  ];
  if (cats.length)
    parts.push(`insert into public.categories (id, name, blurb, sort) values
${cats.map((c) => `  (${[c.id, c.name, c.blurb, c.sort].map(sql).join(", ")})`).join(",\n")}
on conflict (id) do update set name = excluded.name, blurb = excluded.blurb, sort = excluded.sort;`);
  parts.push(`insert into public.products (${cols.join(", ")}) values
${rows}
on conflict (id) do update set
  template = excluded.template, design = excluded.design, name = excluded.name, blurb = excluded.blurb,
  kind = excluded.kind, price_vnd = excluded.price_vnd, sort = excluded.sort, tags = excluded.tags;`);
  parts.push(`-- each product's categories, as its template.json says
delete from public.product_categories where product_id in (${list.map((p) => sql(p.id)).join(", ")});`);
  if (links.length)
    parts.push(`insert into public.product_categories (product_id, category_id) values
${links.join(",\n")};`);
  return parts.join("\n\n") + "\n";
}

if (
  process.argv[1] &&
  fileURLToPath(import.meta.url) === path.resolve(process.argv[1])
) {
  const cats = await categories();
  const list = await products(TEMPLATES, new Set(cats.map((c) => c.id)));
  await fs.writeFile(OUT, seedSql(list, cats));
  console.log(
    `${path.relative(ROOT, OUT)}: ${list.length} products, ${cats.length} categories`,
  );
  for (const p of list)
    console.log(
      `  ${String(p.sort).padStart(3)}  ${p.kind.padEnd(4)}  ${p.id.padEnd(22)} ${p.categories.join(", ")}`,
    );
}
