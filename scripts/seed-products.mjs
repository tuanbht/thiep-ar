#!/usr/bin/env node
/* The shop's products from the templates: one per public/templates/<id> that has a form.json (a buyer needs a form to
   write the card). Writes supabase/seed.sql, which `pnpm db:reset` loads. It upserts every field it knows, prices
   included, so rerunning it on a live database resets prices changed there: change PRICE_VND here instead.
     node scripts/seed-products.mjs     -> supabase/seed.sql
   Order on the shelf: flower-letter first, then the 3D acts, then the films, each alphabetically. */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TEMPLATES = path.join(ROOT, 'public', 'templates');
const OUT = path.join(ROOT, 'supabase', 'seed.sql');
const PRICE_VND = 49000;
const FIRST = 'flower-letter';
const ID = /^[a-z0-9][a-z0-9_-]*$/;

const readJson = async file => JSON.parse(await fs.readFile(file, 'utf8'));
const exists = async file => !!(await fs.stat(file).catch(() => null));
const sql = v => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

/** The products, in shelf order. */
export async function products(dir = TEMPLATES) {
  const found = [];
  for (const id of (await fs.readdir(dir)).sort()) {
    if (!ID.test(id)) continue;
    const t = path.join(dir, id);
    if (!(await exists(path.join(t, 'form.json'))) || !(await exists(path.join(t, 'template.json')))) continue;
    const tpl = await readJson(path.join(t, 'template.json')), form = await readJson(path.join(t, 'form.json'));
    found.push({ id, template: id, design: null, name: String(tpl.name || id).slice(0, 120), blurb: form.label ? String(form.label).slice(0, 300) : null,
      kind: tpl.kind === '3d' ? '3d' : 'film', price_vnd: PRICE_VND, active: true });
  }
  const rank = p => (p.id === FIRST ? 0 : p.kind === '3d' ? 1 : 2);
  found.sort((a, b) => rank(a) - rank(b) || a.id.localeCompare(b.id));
  return found.map((p, i) => ({ ...p, sort: (i + 1) * 10 }));
}

export function seedSql(list) {
  const cols = ['id', 'template', 'design', 'name', 'blurb', 'kind', 'price_vnd', 'active', 'sort'];
  const rows = list.map(p => `  (${cols.map(c => sql(p[c])).join(', ')})`).join(',\n');
  return `-- Generated by scripts/seed-products.mjs from public/templates: do not edit by hand.
insert into public.products (${cols.join(', ')}) values
${rows}
on conflict (id) do update set
  template = excluded.template, design = excluded.design, name = excluded.name, blurb = excluded.blurb,
  kind = excluded.kind, price_vnd = excluded.price_vnd, active = excluded.active, sort = excluded.sort;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const list = await products();
  await fs.writeFile(OUT, seedSql(list));
  console.log(`${path.relative(ROOT, OUT)}: ${list.length} products`);
  for (const p of list) console.log(`  ${String(p.sort).padStart(3)}  ${p.kind.padEnd(4)}  ${p.id}`);
}
